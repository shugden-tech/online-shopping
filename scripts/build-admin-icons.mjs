// Builds src/admin-ui/icons.tsx from Google's Material Symbols (outlined, weight 400; Apache-2.0).
// The icons are inlined as SVG paths so the admin needs no icon font and no request to fonts.google.com
// (the CSP only allows our own origin). To change the set: edit ICONS below, then
//   npm pack @material-symbols/svg-400 && mkdir x && tar -xzf material-symbols-svg-400-*.tgz -C x
//   node scripts/build-admin-icons.mjs x/package
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = {
  // navigation
  dashboard: "dashboard", orders: "receipt_long", products: "liquor", bundles: "redeem", inventory: "inventory_2",
  payments: "payments", shipments: "local_shipping", settings: "settings", audit: "history",
  // actions
  search: "search", save: "save", add: "add", close: "close", refresh: "refresh", filterOff: "filter_alt_off", filter: "filter_list",
  check: "check", doneAll: "done_all", copy: "content_copy", remove: "remove", send: "send", draft: "draft", enable: "toggle_on",
  view: "visibility", retry: "replay", logout: "logout", qr: "qr_code_2", webhook: "webhook",
  external: "open_in_new", back: "arrow_back", forward: "arrow_forward", next: "chevron_right", prev: "chevron_left",
  up: "arrow_upward", down: "arrow_downward", more: "keyboard_arrow_down", key: "key", person: "person", 
  error: "error", info: "info", 
  price: "sell", paid: "paid", 
  low: "low_priority", wait: "hourglass_empty", ok: "check_circle",
  block: "block", store: "store", list: "list_alt",
};

const dir = join(process.argv[2] ?? "x/package", "outlined");
const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(dir, `${file}.svg`), "utf8");
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join("");
  if (!d) throw new Error(`no path in ${file}.svg`);
  out[name] = d;
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: "${v}",`).join("\n");
writeFileSync(
  new URL("../src/admin-ui/icons.tsx", import.meta.url),
  `// GENERATED by scripts/build-admin-icons.mjs — do not edit by hand.
// Icons: Google Material Symbols (outlined, 400), Apache License 2.0, https://fonts.google.com/icons — inlined as SVG paths
// (viewBox 0 -960 960 960, filled with currentColor). Decorative: aria-hidden; put the meaning in the text next to it.
const P = {
${body}
} as const;
export type IconName = keyof typeof P;
export function Icon({ name, size }: { name: IconName; size?: number }) {
  return (
    <svg class="a-ico" viewBox="0 -960 960 960" width={size} height={size} aria-hidden="true" focusable="false"><path d={P[name]} /></svg>
  );
}
`,
);
console.log("icons:", Object.keys(out).length);
