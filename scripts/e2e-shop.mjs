// Phase 3/4 checks: filters, URL state, back/forward, cart persistence.
//   BASE=http://localhost:4321 node scripts/e2e-shop.mjs
import { chromium } from "playwright-core";
const base = process.env.BASE ?? "http://localhost:4321";
const edge = process.env.CHROME_PATH ?? "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe";
const browser = await chromium.launch({ executablePath: edge, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = [];
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
page.on("pageerror", (e) => errors.push(String(e)));
let fails = 0;
const ok = (name, cond, extra = "") => {
  console.log(`${cond ? "PASS" : "FAIL"}  ${name} ${cond ? "" : extra}`);
  if (!cond) fails++;
};
const visible = () => page.$$eval("#shop-grid [data-cell]:not([hidden])", (els) => els.map((e) => e.dataset.cell));
const chip = (text) => page.locator(".flt .chip", { hasText: new RegExp(`^\\s*${text}\\s*$`) }).first().click();
const J = JSON.stringify;

await page.goto(base + "/delguur/", { waitUntil: "networkidle" });
ok("24 cards", (await visible()).length === 24);
await chip("Хув");
ok("family=amber -> 3", (await visible()).length === 3, page.url());
await chip("Модлог");
ok("family amber+woody -> 6", (await visible()).length === 6);
await chip("Эрэгтэй");
ok("+gender men -> bleu only", J(await visible()) === '["bleu-de-chanel"]', J(await visible()));
ok("url has state", page.url().includes("family=amber,woody") && page.url().includes("gender=men"), page.url());
await page.goBack();
await page.waitForTimeout(900);
ok("back -> 6", (await visible()).length === 6, page.url());
ok("back: chip state restored", (await page.locator('.flt .chip[aria-pressed="true"]').count()) === 2);
await page.goBack();
await page.waitForTimeout(900);
ok("back -> 3", (await visible()).length === 3, page.url());
await page.goForward();
await page.waitForTimeout(900);
ok("forward -> 6", (await visible()).length === 6, page.url());
await page.locator("#shop-grid [data-cell]:not([hidden]) .pcard__name a").first().click();
await page.waitForURL(/delguur\/[a-z0-9-]+\/$/);
await page.waitForTimeout(600);
ok("navigated to product", (await page.locator(".pdp__name").count()) === 1, page.url());
await page.goBack();
await page.waitForTimeout(900);
ok("back from product keeps filters", (await visible()).length === 6 && page.url().includes("family=amber,woody"), page.url());

await page.goto(base + "/delguur/?notes=oud", { waitUntil: "networkidle" });
ok("notes=oud", J(await visible()) === '["oud-wood"]', J(await visible()));
await page.goto(base + "/delguur/?notes=vanilla,woods&sort=price-asc", { waitUntil: "networkidle" });
const vw = await visible();
ok("notes AND + sort asc", vw.length > 2 && vw[0] === "eros", J(vw));
await page.goto(base + "/delguur/?size=30", { waitUntil: "networkidle" });
ok("size=30 -> 2", (await visible()).length === 2);
await page.goto(base + "/delguur/?min=40000&max=42000", { waitUntil: "networkidle" });
ok("price 40-42k", J((await visible()).sort()) === '["angels-share","baccarat-rouge-540"]', J(await visible()));
await page.goto(base + "/delguur/?season=summer&occasion=date", { waitUntil: "networkidle" });
ok("season+occasion", (await visible()).includes("neroli-portofino"), J(await visible()));
await page.goto(base + "/delguur/", { waitUntil: "networkidle" });
await page.fill("#search", "acqua di gio");
ok("search ignores diacritics (gio)", J(await visible()) === '["acqua-di-gio"]', J(await visible()));
await page.fill("#search", "гургэм");
ok("search folds mn letters (гургэм)", J(await visible()) === '["baccarat-rouge-540"]', J(await visible()));
await page.fill("#search", "zzzz");
ok("empty state shown", await page.locator("#shop-empty").isVisible());
await page.click("[data-clear-filters]");
ok("clear -> 24", (await visible()).length === 24);
await page.selectOption(".flt__sort select", "price-desc");
ok("sort price desc", (await visible())[0] === "aventus", (await visible())[0]);
await page.selectOption(".flt__sort select", "az");
ok("sort az", (await visible())[0] === "acqua-di-gio");

await page.goto(base + "/en/shop/?family=citrus", { waitUntil: "networkidle" });
ok("en shop filter", (await visible()).length === 3 && (await page.locator("h1").innerText()) === "Shop");
await page.goto(base + "/en/shop/sauvage/", { waitUntil: "networkidle" });
ok("en product", (await page.locator(".atc__btn").innerText()).toLowerCase().includes("add to cart"));
ok("json-ld", (await page.locator('script[type="application/ld+json"]').innerText()).includes('"@type":"Product"'));

// ---- cart ----
await page.goto(base + "/delguur/sauvage/", { waitUntil: "networkidle" });
await page.locator(".atc__chip", { hasText: "36,000" }).click();
await page.click(".atc__btn");
await page.waitForSelector(".cd[data-open]");
ok("drawer opened with 1 line", (await page.locator(".cd__item").count()) === 1);
await page.keyboard.press("Escape");
await page.waitForTimeout(700);
ok("esc closes drawer", (await page.locator(".cd[data-open]").count()) === 0);
await page.locator(".atc__chip", { hasText: "66,000" }).click();
await page.locator(".atc .stepper button").nth(1).click();
await page.click(".atc__btn");
await page.waitForSelector(".cd[data-open]");
await page.keyboard.press("Escape");
await page.waitForTimeout(600);
await page.goto(base + "/delguur/", { waitUntil: "networkidle" });
await page.locator('[data-cell="oud-wood"] [data-add]').click();
await page.waitForSelector(".cd[data-open]");
ok("3 lines", (await page.locator(".cd__item").count()) === 3);
// sauvage 5 ml 36,000 + 10 ml 66,000 x2 + oud wood 2 ml 36,000 = 204,000
const sum = () => page.locator(".cd__sum strong").innerText();
ok("subtotal 204,000", (await sum()) === "204,000₮", await sum());
ok("badge 4", (await page.locator("[data-cart-count]").first().innerText()) === "4");
await page.reload({ waitUntil: "networkidle" });
ok("badge persists after reload", (await page.locator("[data-cart-count]").first().innerText()) === "4");
await page.click(".hdr__cart");
await page.waitForSelector(".cd[data-open]");
ok("cart persists after reload", (await page.locator(".cd__item").count()) === 3);
await page.locator(".cd__item").nth(0).locator(".stepper button").nth(1).click();
ok("qty + -> 240,000", (await sum()) === "240,000₮", await sum());
await page.locator(".cd__item").nth(0).locator(".stepper button").nth(0).click();
await page.locator(".cd__item").nth(1).locator(".cd__remove").click();
ok("remove -> 2 lines, 72,000", (await page.locator(".cd__item").count()) === 2 && (await sum()) === "72,000₮", await sum());
ok("free delivery hint", (await page.locator(".cd__free p").innerText()).includes("28,000₮"), await page.locator(".cd__free p").innerText());
await page.waitForTimeout(600);
await page.screenshot({ path: "docs/screens/p4-cart-drawer-1440.png" });
console.log("console errors:", errors.length ? errors : "none");
console.log(fails ? `${fails} FAILED` : "ALL PASSED");
await browser.close();
process.exit(fails ? 1 : 0);
